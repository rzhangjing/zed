#!/usr/bin/env bash
# Renders the PKGBUILD of the `rustgis-bin` AUR package for one release.
#
#   packaging/aur/render.sh <version> <SHA256SUMS> > PKGBUILD
#
# A binary package: it unpacks the release's .deb (x86_64 and aarch64), which already carries
# both programs, the desktop entry, the project file type and the icons, so installing it needs
# no Rust toolchain. The checksums come from the release's SHA256SUMS. REPO defaults to
# opengeos/RustGIS.
set -euo pipefail

version="${1:?usage: render.sh <version> <SHA256SUMS>}"
version="${version#v}"
sums="${2:?usage: render.sh <version> <SHA256SUMS>}"
repo="${REPO:-opengeos/RustGIS}"

# pkgver may not contain a hyphen, so pre-releases are never published.
[[ "$version" =~ ^[0-9]+\.[0-9]+\.[0-9]+$ ]] || { echo "not an X.Y.Z version: $version" >&2; exit 1; }
[[ "$repo" =~ ^[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+$ ]] || { echo "REPO is not owner/name: $repo" >&2; exit 1; }

sha() {
  local h
  h="$(awk -v f="$1" '$2 == f || $2 == "*" f { print $1 }' "$sums")"
  [[ "$h" =~ ^[0-9a-f]{64}$ ]] || { echo "no checksum for $1 in $sums" >&2; return 1; }
  echo "$h"
}

amd64="$(sha "rustgis_${version}_amd64.deb")"
arm64="$(sha "rustgis_${version}_arm64.deb")"

# Escaped \$ stays a makepkg variable in the PKGBUILD.
cat <<PKGBUILD
# Maintainer: Qiusheng Wu <giswqs@gmail.com>
#
# Generated by packaging/aur/render.sh in https://github.com/$repo and published by its
# release workflow; edit the script there, not this file.
pkgname=rustgis-bin
pkgver=$version
pkgrel=1
pkgdesc="Fast, free and open-source GIS for mapping, analyzing and sharing geospatial data"
arch=('x86_64' 'aarch64')
url="https://rustgis.app"
license=('Apache-2.0')
depends=('gcc-libs' 'glibc' 'hicolor-icon-theme' 'libxkbcommon')
# The window system and GPU libraries are loaded at run time.
optdepends=('wayland: Wayland sessions'
            'libx11: X11 sessions'
            'libxcursor: X11 sessions'
            'libxi: X11 sessions'
            'libxrandr: X11 sessions'
            'libxkbcommon-x11: X11 sessions'
            'vulkan-icd-loader: drawing with Vulkan'
            'libglvnd: drawing with OpenGL'
            'gdal: reading the vector formats GDAL supports')
provides=('rustgis')
conflicts=('rustgis')
options=('!strip' '!debug')
source_x86_64=("rustgis-\${pkgver}-x86_64.deb::https://github.com/$repo/releases/download/v\${pkgver}/rustgis_\${pkgver}_amd64.deb")
source_aarch64=("rustgis-\${pkgver}-aarch64.deb::https://github.com/$repo/releases/download/v\${pkgver}/rustgis_\${pkgver}_arm64.deb")
sha256sums_x86_64=('$amd64')
sha256sums_aarch64=('$arm64')
noextract=("rustgis-\${pkgver}-\${CARCH}.deb")

package() {
	cd "\${srcdir}"
	# A .deb is an ar archive; the files are in its data.tar (compressed with zstd, xz or gzip).
	bsdtar -xf "rustgis-\${pkgver}-\${CARCH}.deb"
	local data=(data.tar.*)
	[[ -f \${data[0]} ]] || { echo "no data.tar in the .deb" >&2; return 1; }
	bsdtar -xpf "\${data[0]}" -C "\${pkgdir}"
	# Arch keeps license texts under /usr/share/licenses, not the Debian copyright file.
	install -Dm644 "\${pkgdir}/usr/share/doc/rustgis/copyright" "\${pkgdir}/usr/share/licenses/\${pkgname}/LICENSE"
	rm -r "\${pkgdir}/usr/share/doc"
}
PKGBUILD
