#!/usr/bin/env bash
# Renders the Fedora COPR package (giswqs/rustgis) for one release into a folder: rustgis.spec
# and the AppStream metainfo it installs.
#
#   packaging/copr/render.sh <version> <release date YYYY-MM-DD> <folder>
#
# A binary package: the spec repackages the release's own .rpm (x86_64 and aarch64, as Source0
# and Source1) and adds the metainfo, which gives RustGIS a page in GNOME Software and KDE
# Discover. Build the source RPM with both release .rpm files and the metainfo in SOURCES.
# REPO defaults to opengeos/RustGIS.
set -euo pipefail

version="${1:?usage: render.sh <version> <date> <folder>}"
version="${version#v}"
date="${2:?usage: render.sh <version> <date> <folder>}"
out="${3:?usage: render.sh <version> <date> <folder>}"
repo="${REPO:-opengeos/RustGIS}"

[[ "$version" =~ ^[0-9]+\.[0-9]+\.[0-9]+$ ]] || { echo "not an X.Y.Z version: $version" >&2; exit 1; }
[[ "$repo" =~ ^[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+$ ]] || { echo "REPO is not owner/name: $repo" >&2; exit 1; }
[[ "$date" =~ ^[0-9]{4}-[0-9]{2}-[0-9]{2}$ && "$(date -u -d "$date" +%F 2> /dev/null)" == "$date" ]] \
  || { echo "not a YYYY-MM-DD date: $date" >&2; exit 1; }
# rpm wants "Mon Oct 12 2026" in %changelog.
changelog_date="$(LC_ALL=C date -u -d "$date" +"%a %b %d %Y")"
appid=org.rustgis.RustGIS
mkdir -p "$out"

cat > "$out/$appid.metainfo.xml" <<XML
<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by packaging/copr/render.sh in $repo for each release. -->
<component type="desktop-application">
  <id>$appid</id>
  <metadata_license>CC0-1.0</metadata_license>
  <project_license>Apache-2.0</project_license>
  <name>RustGIS</name>
  <summary>Fast, free and open-source GIS</summary>
  <description>
    <p>
      RustGIS is a geographic information system for mapping, analyzing and sharing
      geospatial data: one native program, drawn on the GPU, that also runs in the browser.
    </p>
    <ul>
      <li>GeoJSON, CSV, Shapefile, GeoPackage, GeoParquet, FlatGeobuf, PMTiles and GeoTIFF</li>
      <li>Symbology, labels, page layouts, reports and PDF export</li>
      <li>Editing with snapping, topology and undo for every change</li>
      <li>Geoprocessing, plus over 1,000 GeoLibre and Whitebox tools</li>
      <li>An AI Assistant, sandboxed plugins and rustgis-cli for scripting every command</li>
    </ul>
  </description>
  <launchable type="desktop-id">rustgis.desktop</launchable>
  <url type="homepage">https://rustgis.app</url>
  <url type="bugtracker">https://github.com/$repo/issues</url>
  <url type="vcs-browser">https://github.com/$repo</url>
  <developer id="app.rustgis">
    <name>RustGIS</name>
  </developer>
  <categories>
    <category>Science</category>
    <category>Geography</category>
  </categories>
  <keywords>
    <keyword>GIS</keyword>
    <keyword>map</keyword>
    <keyword>geospatial</keyword>
    <keyword>GeoJSON</keyword>
    <keyword>shapefile</keyword>
  </keywords>
  <provides>
    <binary>rustgis</binary>
    <binary>rustgis-cli</binary>
  </provides>
  <screenshots>
    <screenshot type="default">
      <image>https://assets.rustgis.app/images/hero.webp</image>
      <caption>A map in RustGIS with the ribbon, Contents pane and attribute table</caption>
    </screenshot>
  </screenshots>
  <content_rating type="oars-1.1"/>
  <releases>
    <release version="$version" date="$date">
      <url type="details">https://github.com/$repo/releases/tag/v$version</url>
    </release>
  </releases>
</component>
XML

# Escaped \$ stays literal for rpmbuild.
cat > "$out/rustgis.spec" <<SPEC
# Generated by packaging/copr/render.sh in https://github.com/$repo for each release.
# The payload is the release's own build, so skip the post-processing meant for compiled code.
# Library dependencies are still found in the binaries.
%global debug_package %{nil}
%global __os_install_post %{nil}
%global _build_id_links none
%global appid $appid

Name:           rustgis
Version:        $version
Release:        1%{?dist}
Summary:        Fast, free and open-source GIS
License:        Apache-2.0
URL:            https://rustgis.app
ExclusiveArch:  x86_64 aarch64

Source0:        https://github.com/$repo/releases/download/v%{version}/rustgis-%{version}-1.x86_64.rpm
Source1:        https://github.com/$repo/releases/download/v%{version}/rustgis-%{version}-1.aarch64.rpm
Source2:        %{appid}.metainfo.xml

BuildRequires:  cpio
BuildRequires:  desktop-file-utils
BuildRequires:  libappstream-glib

# The window system and GPU libraries are loaded at run time, so they are not found
# automatically.
Requires:       libxkbcommon.so.0()(64bit)
Requires:       (libwayland-client.so.0()(64bit) or libX11.so.6()(64bit))
Recommends:     libxkbcommon-x11.so.0()(64bit)
Recommends:     libXcursor.so.1()(64bit)
Recommends:     libXi.so.6()(64bit)
Recommends:     libXrandr.so.2()(64bit)
Recommends:     (libvulkan.so.1()(64bit) or libEGL.so.1()(64bit))

%description
RustGIS is a geographic information system for mapping, analyzing and sharing
geospatial data: maps and layers, symbology, labels, editing, geoprocessing,
page layouts and export. It includes rustgis-cli for scripting every command.

%prep

%build

%install
%ifarch x86_64
rpm=%{SOURCE0}
%else
rpm=%{SOURCE1}
%endif
mkdir -p %{buildroot}
cd %{buildroot}
rpm2cpio "\$rpm" | cpio -idm --quiet
rm -rf %{buildroot}/usr/lib/.build-id
install -Dm644 %{SOURCE2} %{buildroot}%{_metainfodir}/%{appid}.metainfo.xml

%check
desktop-file-validate %{buildroot}%{_datadir}/applications/rustgis.desktop
appstream-util validate-relax --nonet %{buildroot}%{_metainfodir}/%{appid}.metainfo.xml

%files
%license %{_docdir}/rustgis/copyright
%{_bindir}/rustgis
%{_bindir}/rustgis-cli
%{_datadir}/applications/rustgis.desktop
%{_datadir}/mime/packages/rustgis.xml
%{_datadir}/icons/hicolor/*/apps/rustgis.png
%{_metainfodir}/%{appid}.metainfo.xml

%changelog
* $changelog_date Qiusheng Wu <giswqs@gmail.com> - $version-1
- RustGIS $version: https://github.com/$repo/releases/tag/v$version
SPEC
